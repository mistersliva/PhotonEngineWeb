pub struct BitmapFont;

pub const CHAR_W: u32 = 8;
pub const CHAR_H: u32 = 8;
pub const ATLAS_COLS: u32 = 16;
pub const ATLAS_ROWS: u32 = 6;
pub const ATLAS_W: u32 = ATLAS_COLS * CHAR_W;
pub const ATLAS_H: u32 = ATLAS_ROWS * CHAR_H;

pub fn generate_atlas_pixels() -> Vec<u8> {
    let mut pixels = vec![0u8; (ATLAS_W * ATLAS_H * 4) as usize];
    for code in 32u32..127u32 {
        let glyph_index = (code - 32) as usize;
        let col = glyph_index % ATLAS_COLS as usize;
        let row = glyph_index / ATLAS_COLS as usize;
        let glyph = GLYPHS[glyph_index];
        for gy in 0..8usize {
            let bits = glyph[gy];
            for gx in 0..8usize {
                if bits & (0x80 >> gx) != 0 {
                    let px = (col as u32 * CHAR_W + gx as u32) as usize;
                    let py = (row as u32 * CHAR_H + gy as u32) as usize;
                    let idx = (py * ATLAS_W as usize + px) * 4;
                    pixels[idx] = 255;
                    pixels[idx + 1] = 255;
                    pixels[idx + 2] = 255;
                    pixels[idx + 3] = 255;
                }
            }
        }
    }
    pixels
}

pub fn char_uvs(ch: char) -> Option<(f32, f32, f32, f32)> {
    let code = ch as u32;
    if code < 32 || code >= 127 {
        return None;
    }
    let idx = (code - 32) as f32;
    let col = idx % ATLAS_COLS as f32;
    let row = (idx / ATLAS_COLS as f32).floor();
    let u0 = col / ATLAS_COLS as f32;
    let v0 = row / ATLAS_ROWS as f32;
    let u1 = (col + 1.0) / ATLAS_COLS as f32;
    let v1 = (row + 1.0) / ATLAS_ROWS as f32;
    Some((u0, v0, u1, v1))
}

pub fn char_width_in_clip(screen_width: f32, _char_count: f32) -> f32 {
    (CHAR_H as f32 / screen_width as f32) * 1.5
}

